import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const listings = JSON.parse(fs.readFileSync(path.join(root, 'shared/listings.json'), 'utf8'))
const categories = JSON.parse(fs.readFileSync(path.join(root, 'shared/categories.json'), 'utf8'))

const header = `// Generated by scripts/sync-data.mjs — do not edit by hand.\n// Source: shared/listings.json and shared/categories.json\n\n`
const body = `export const seedListings = ${JSON.stringify(listings, null, 2)}\n\nexport const categories = ${JSON.stringify(categories, null, 2)}\n`
fs.writeFileSync(path.join(root, 'server/vercel/data.mjs'), header + body)
console.log(`Synced ${listings.length} listings and ${categories.length} categories into server/vercel/data.mjs`)
